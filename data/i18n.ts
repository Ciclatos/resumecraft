const localizedValues: Record<string, TranslationKey> = {
  actualidad: "status.present",
  present: "status.present",
  current: "status.present",
  nativo: "status.native",
  native: "status.native",
  profesional: "status.professional",
  professional: "status.professional",
  fluido: "status.fluent",
  fluent: "status.fluent",
  basico: "status.basic",
  basic: "status.basic",
};

export function t(language: AppLanguage | undefined, key: TranslationKey) {
  return translations[language ?? "es"][key] ?? translations.es[key];
}

export function localizeFixedValue(language: AppLanguage | undefined, value: string) {
  return value.replace(/\b(actualidad|present|current|nativo|native|profesional|professional|fluido|fluent|básico|basico|basic)\b/gi, (match) => {
    const key = localizedValues[normalizeMatch(match)];

    return key ? t(language, key) : match;
  });
}

function normalizeMatch(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}
